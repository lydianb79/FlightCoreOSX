// The 45 steps of the Flight Academy. Every one is flown to a pass by the instructor pilot of `--academytest`,
// so run that after changing a step, or anything in the flight model.
//
// Coordinates: the pilot stands at +z looking toward -z, +x is to the pilot's right, and y is above the ground.

private let east = V3(1, 0, 0), west = V3(-1, 0, 0), away = V3(0, 0, -1), atPilot = V3(0, 0, 1)

private func gate(_ text: String, _ x: Float, _ y: Float, _ z: Float, _ dir: V3, w: Float, h: Float, pose: Pose = .any, via: Pose? = nil) -> AcademyTask {
    AcademyTask(text: text, kind: .pass(via: via), box: TargetBox(center: V3(x, y, z), size: V3(w, h, 1.2), dir: dir), pose: pose)
}
/// `size` is width (across the flight), height, length.
private func hold(_ text: String, _ seconds: Float, _ at: V3, _ size: V3, _ pose: Pose, dir: V3 = east) -> AcademyTask {
    AcademyTask(text: text, kind: .hold(seconds: seconds), box: TargetBox(center: at, size: size, dir: dir), pose: pose)
}
private func rotate(_ text: String, _ axis: Spin, _ degrees: Float, _ at: V3, _ size: V3, pose: Pose = .any, slowest: Float = 0, dir: V3 = east) -> AcademyTask {
    AcademyTask(text: text, kind: .rotate(axis, degrees: degrees, slowest: slowest), box: TargetBox(center: at, size: size, dir: dir), pose: pose)
}
private func pad(_ text: String, _ x: Float, _ z: Float, width: Float, length: Float, dir: V3 = east) -> AcademyTask {
    AcademyTask(text: text, kind: .land, box: TargetBox(center: V3(x, 0.3, z), size: V3(width, 0.6, length), dir: dir))
}

